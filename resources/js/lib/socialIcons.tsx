/**
 * Example URL shown in the link input. Most platforms are `<name>.com/<handle>`, but
 * a few are not, and a wrong example leads users to paste something that does not resolve:
 * Telegram handles live on t.me and a WhatsApp link is wa.me/<phone number>, not a website.
 */
const LINK_PLACEHOLDERS: Record<string, string> = {
    telegram: 'https://t.me/your-handle',
    whatsapp: 'https://wa.me/15551234567',
};

export function placeholderFor(name: string): string {
    const key = name.toLowerCase();

    return LINK_PLACEHOLDERS[key] ?? `https://${key}.com/your-profile`;
}